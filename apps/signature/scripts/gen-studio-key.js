#!/usr/bin/env node
// gen-studio-key.js - writes the generated/StudioKey.h that compiles the studio
// key into MIREKU (engine/Sealed.h). Run by CMake at configure time; never by
// hand, and the output is never committed (it lives in the build folder).
//
//   node gen-studio-key.js --out <path/StudioKey.h> [--allow-test]
//
// The key is looked up the way the packer does (packages/aofas-format/src/keyring.ts):
//   1. AOFAS_STUDIO_KEY, 64 hex characters (CI), with AOFAS_STUDIO_KEY_ID (default 1)
//   2. AOFAS_KEYFILE, else ~/.amanorsac/studio-keys.json  { "keys": {"1": "<hex>"}, "activeKeyId": 1 }
//   3. with --allow-test only: the documented all-zero TEST key, and the header
//      says so (kIsTestKey = true). The installer scripts refuse to package a
//      binary built from such a header; a developer build without the key
//      still compiles and runs the tests, which seal their own fixtures.
//
// The key is written as two random XOR shares, not as 32 contiguous bytes
// (spec section 4, "obfuscated key storage"): a strings-and-grep attack on the
// binary finds nothing.
'use strict';
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const crypto = require('node:crypto');

const args = process.argv.slice(2);
const flag = (name) => { const i = args.indexOf('--' + name); return i >= 0 ? args[i + 1] : undefined; };
const out = flag('out');
if (!out) { console.error('usage: gen-studio-key.js --out <StudioKey.h> [--allow-test]'); process.exit(2); }
const allowTest = args.includes('--allow-test');

function fromHex(hex, where) {
  const b = Buffer.from(String(hex).trim(), 'hex');
  if (b.length !== 32) throw new Error(`${where}: expected 64 hex characters`);
  return b;
}

let key = null, keyId = 1, isTest = false, source = '';
if (process.env.AOFAS_STUDIO_KEY) {
  key = fromHex(process.env.AOFAS_STUDIO_KEY, 'AOFAS_STUDIO_KEY');
  keyId = Number(process.env.AOFAS_STUDIO_KEY_ID || 1);
  source = 'AOFAS_STUDIO_KEY';
} else {
  const file = process.env.AOFAS_KEYFILE || path.join(os.homedir(), '.amanorsac', 'studio-keys.json');
  if (fs.existsSync(file)) {
    const doc = JSON.parse(fs.readFileSync(file, 'utf8'));
    const keys = doc.keys || {};
    keyId = Number(doc.activeKeyId || Math.max(...Object.keys(keys).map(Number)));
    if (!keys[String(keyId)]) throw new Error(`${file}: activeKeyId ${keyId} is not in "keys"`);
    key = fromHex(keys[String(keyId)], `${file} key ${keyId}`);
    source = file;
  }
}
if (!key) {
  if (!allowTest) {
    console.error('No studio key: set AOFAS_STUDIO_KEY or create ~/.amanorsac/studio-keys.json (npx aofas keygen).');
    process.exit(1);
  }
  key = Buffer.alloc(32, 0);
  keyId = 1;
  isTest = true;
  source = 'TEST KEY (all zero) - not for any build that leaves this machine';
}
if (!(keyId >= 1 && keyId <= 255)) throw new Error(`keyId ${keyId} is out of range`);

const shareA = crypto.randomBytes(32);
const shareB = Buffer.alloc(32);
for (let i = 0; i < 32; ++i) shareB[i] = shareA[i] ^ key[i];
const list = (b) => Array.from(b).map((x) => '0x' + x.toString(16).padStart(2, '0')).join(', ');

const text = `// Generated by apps/signature/scripts/gen-studio-key.js at configure time. DO NOT COMMIT.
// Source: ${isTest ? source : 'the studio key file (not named here)'}
#pragma once
#include <cstdint>
namespace jm::sealed::studiokey {
inline constexpr uint8_t kKeyId = ${keyId};
inline constexpr bool kIsTestKey = ${isTest ? 'true' : 'false'};
inline constexpr uint8_t kShareA[32] = { ${list(shareA)} };
inline constexpr uint8_t kShareB[32] = { ${list(shareB)} };
} // namespace jm::sealed::studiokey
`;
fs.mkdirSync(path.dirname(out), { recursive: true });
// Only rewrite when the KEY changed, so an unchanged configure does not rebuild
// everything that includes the header (the shares are random per write).
let same = false;
if (fs.existsSync(out)) {
  const prev = fs.readFileSync(out, 'utf8');
  const m = prev.match(/kShareA\[32\] = \{([^}]*)\}[\s\S]*kShareB\[32\] = \{([^}]*)\}/);
  const idm = prev.match(/kKeyId = (\d+)/), tm = prev.match(/kIsTestKey = (true|false)/);
  if (m && idm && tm) {
    const a = m[1].split(',').map((s) => Number(s.trim())), b = m[2].split(',').map((s) => Number(s.trim()));
    same = a.length === 32 && Number(idm[1]) === keyId && (tm[1] === 'true') === isTest
      && a.every((x, i) => (x ^ b[i]) === key[i]);
  }
}
if (!same) fs.writeFileSync(out, text);
console.log(`StudioKey.h: keyId ${keyId}${isTest ? ' TEST KEY' : ''} (${same ? 'unchanged' : 'written'})`);
