// make-licence-test-vectors.js — signed proofs for the licence unit tests.
//
// The licence client (src/license) verifies a server proof with the studio's
// P-256 public key. The tests cannot use that key: only the live server holds
// its private half. So this script makes a THROWAWAY pair, signs proofs in the
// server's exact wire format (License Integration Standard, section 5) and
// writes the public half plus the proofs into tests/LicenceVectors.inc.
//
// The private half is never written anywhere. The public half lives in the test
// binaries only; a release contains the studio key and no other (R2), which the
// installer scripts check in the bytes.
//
//   node scripts/make-licence-test-vectors.js
'use strict';
const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const { publicKey, privateKey } = crypto.generateKeyPairSync('ec', { namedCurve: 'P-256' });
const jwk = publicKey.export({ format: 'jwk' });
const pub = Buffer.concat([Buffer.from([4]), Buffer.from(jwk.x, 'base64url'), Buffer.from(jwk.y, 'base64url')]);

const DEVICE = '3f7c2a9e-6b1d-4e2f-9a8c-1d2e3f4a5b6c';
const KEY = 'TEST-610E-6070-3493';
const ISSUED = 1800000000000;
const H = 3600 * 1000, D = 24 * H;

const body = (o) => Buffer.from(JSON.stringify(o), 'utf8');
const sign = (b, enc) => crypto.sign('sha256', b, { key: privateKey, dsaEncoding: enc });
const proof = (b, s) => b.toString('base64url') + '.' + s.toString('base64url');

const good = body({ deviceKey: DEVICE, licenseKey: KEY, issuedAt: ISSUED, expiresAt: ISSUED + 48 * H, graceUntil: ISSUED + 30 * D });
const goodSig = sign(good, 'ieee-p1363');

// the same signature over a body whose grace window was edited by hand
const tampered = body({ deviceKey: DEVICE, licenseKey: KEY, issuedAt: ISSUED, expiresAt: ISSUED + 48 * H, graceUntil: ISSUED + 3000 * D });

const hex = (b) => {
  const rows = [];
  for (let i = 0; i < b.length; i += 12)
    rows.push('    ' + [...b.subarray(i, i + 12)].map((x) => '0x' + x.toString(16).padStart(2, '0')).join(', '));
  return rows.join(',\n');
};

const out = `// LicenceVectors.inc — GENERATED by scripts/make-licence-test-vectors.js.
// A throwaway P-256 pair: the private half was never written down. TEST BINARIES
// ONLY; a release carries the studio key and no other (Licence Standard R2).
static const juce::uint8 kLicenceTestKey[65] = {
${hex(pub)}
};
static const char* const kLicenceTestDevice = "${DEVICE}";
static const char* const kLicenceTestLicence = "${KEY}";
static const juce::int64 kLicenceTestIssued = ${ISSUED}LL;
/// a genuine proof: raw r||s signature over the body
static const char* const kLicenceProofGood =
    "${proof(good, goodSig)}";
/// the genuine signature attached to an edited body
static const char* const kLicenceProofTampered =
    "${proof(tampered, goodSig)}";
/// a correct signature in DER, which the standard says to reject (64 bytes only)
static const char* const kLicenceProofDer =
    "${proof(good, sign(good, 'der'))}";
`;
const target = path.join(__dirname, '..', 'tests', 'LicenceVectors.inc');
fs.writeFileSync(target, out);
console.log('wrote ' + target);
