# Writes src/engine/FactoryPresets.h for Top End and Low End from the recipes
# in factory_top.py / factory_low.py. Each preset has a permanent key: the app
# installs any key it has not installed before, so an update adds new presets
# without bringing back ones a player deleted.
#   python gen-factory.py
import io, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
APPS = os.path.join(HERE, '..', '..', '..', 'apps')

def slug(s):
    return re.sub(r'[^a-z0-9]+', '-', s.lower()).strip('-')

def cpp_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

def num(v):
    if isinstance(v, bool): return '1' if v else '0'
    if isinstance(v, int): return str(v)
    t = ('%.3f' % v).rstrip('0').rstrip('.')
    return t + ('.0f' if '.' not in t else 'f')

def emit(app, ns, label, presets, v1, demos, cats):
    keys = set()
    rows = []
    for p in presets:
        key = p.get('key') or slug(p['name'])
        assert key not in keys, ('duplicate key', app, key)
        keys.add(key)
        edits = []
        for sec in ('amp', 'cab', 'in', 'synth', 'loop'):
            for k, v in p.get(sec, {}).items(): edits.append((sec + '.' + k, v))
        for chain in ('pre', 'post'):
            for i, (t, params) in enumerate(p.get(chain, [])):
                for k, v in params.items(): edits.append(('%s.%d.%s' % (chain, i, k), v))
                if params.get('_off'): pass
        pre = ', '.join('BlockType::' + t for t, _ in p.get('pre', []))
        post = ', '.join('BlockType::' + t for t, _ in p.get('post', []))
        ed = ', '.join('{ %s, %s }' % (cpp_str(a), num(b)) for a, b in edits if not a.endswith('._off'))
        assert p['cat'] in cats, (app, p['name'], p['cat'])
        rows.append('        { %s, %s, %s, 0xff%s,\n          { %s },\n          { %s },\n          { %s } },'
                    % (cpp_str(key), cpp_str(p['name']), cpp_str(p['cat']), p['col'].lstrip('#').upper(), pre, post, ed))
    for k in v1: assert k in keys, ('v1 key missing', k)
    for d in demos:
        for k in d[2]: assert k in keys, ('demo key missing', k)
    demo_rows = ',\n'.join('        { %s, %s, { %s } }' % (cpp_str(n), num(float(t)), ', '.join(cpp_str(k) for k in ks)) for n, t, ks in demos)
    v1_rows = ', '.join(cpp_str(k) for k in v1)
    cat_rows = ', '.join(cpp_str(c) for c in cats)
    src = '''#pragma once
// GENERATED by shared/ui-build/factory/gen-factory.py - edit the recipes there.
//
// The factory library: %(n)d presets. Each has a permanent key. On every launch
// the app installs any factory preset whose key it has not installed before and
// records the key, so an update adds new presets without bringing back one the
// player deleted. The presets from before keys existed are matched by name.

namespace %(ns)s {

struct FactoryEdit { const char* path; float value; };
struct FactoryPreset
{
    const char* key;
    const char* name;
    const char* category;
    juce::uint32 colour;
    std::vector<BlockType> pre, post;
    std::vector<FactoryEdit> edits;
};

/// The Library's categories, in the order its filters show them.
inline const std::vector<const char*>& factoryCategories()
{
    static const std::vector<const char*> c { %(cats)s };
    return c;
}

inline const std::vector<FactoryPreset>& factoryPresets()
{
    static const std::vector<FactoryPreset> f {
%(rows)s
    };
    return f;
}

/// Builds one factory preset as a rig. Unknown paths are logged, never fatal.
inline Rig makeFactoryRig (const FactoryPreset& f, int order)
{
    Rig r = defaultRig (f.name);
    r.colour = f.colour;
    r.order = order;
    r.category = f.category;
    r.factoryKey = f.key;
    r.pre.clear();
    for (auto t : f.pre) r.pre.push_back (defaultBlockState (t));
    r.post.clear();
    for (auto t : f.post) r.post.push_back (defaultBlockState (t));
    for (auto& e : f.edits)
        if (! setPath (r, e.path, e.value))
            juce::Logger::writeToLog (juce::String ("%(label)s factory: unknown path ") + e.path + " in preset " + f.name);
    return r;
}

inline void RigLibrary::syncFactory()
{
    appDataDir().createDirectory();
    scan();                        // what is on disk now: needed to recognise the first library's presets
    const auto ledger = appDataDir().getChildFile ("factory-keys.txt");
    const auto v1Marker = appDataDir().getChildFile ("factory-v1.txt");
    juce::StringArray done;
    if (ledger.existsAsFile() && ledger.getSize() < 256 * 1024)
        done.addLines (ledger.loadFileAsString());
    done.trim(); done.removeEmptyStrings();
    const bool firstRun = done.isEmpty() && ! v1Marker.existsAsFile();

    const auto& list = factoryPresets();
    auto orderOf = [&list] (const juce::String& key) { for (size_t i = 0; i < list.size(); ++i) if (key == list[i].key) return (int) i; return 1000; };

    // Upgrading from the first factory library: its presets are already here
    // (or the player deleted them). Give the survivors their key and category.
    if (done.isEmpty() && v1Marker.existsAsFile())
    {
        static const char* const v1[] { %(v1)s };
        for (auto* k : v1) done.addIfNotAlreadyThere (k);
        for (auto r : presets_)
        {
            if (r.factoryKey.isNotEmpty()) continue;
            for (auto& f : list)
                if (r.name == f.name && done.contains (f.key))
                {
                    r.factoryKey = f.key; r.category = f.category; r.order = orderOf (f.key);
                    savePreset (r);
                    break;
                }
        }
    }

    juce::StringArray made;
    for (size_t i = 0; i < list.size(); ++i)
    {
        if (done.contains (list[i].key)) continue;
        savePreset (makeFactoryRig (list[i], (int) i));
        done.add (list[i].key);
        made.add (list[i].key);
    }
    if (made.isEmpty() && ledger.existsAsFile()) return;
    ledger.replaceWithText (done.joinIntoString ("\\n") + "\\n");

    if (! firstRun) return;
    // Demo sets on a first launch only, built from the presets just made.
    struct Demo { const char* name; double tempo; std::vector<const char*> keys; };
    const std::vector<Demo> demos {
%(demos)s
    };
    auto idOf = [this] (const char* key) { for (auto& r : presets_) if (r.factoryKey == key) return r.id; return juce::String(); };
    juce::StringArray songIds;
    for (auto& d : demos)
    {
        Song s;
        s.name = d.name;
        s.tempo = d.tempo;
        for (auto* k : d.keys) if (auto id = idOf (k); id.isNotEmpty()) s.presetIds.add (id);
        songIds.add (saveSong (std::move (s)));
    }
    Setlist set;
    set.name = "Demo Set";
    set.songIds = songIds;
    saveSetlist (std::move (set));
}

} // namespace %(ns)s
''' % dict(n=len(presets), ns=ns, label=label, rows='\n'.join(rows), v1=v1_rows, demos=demo_rows, cats=cat_rows)
    out = os.path.join(APPS, app, 'src', 'engine', 'FactoryPresets.h')
    io.open(out, 'w', encoding='utf-8', newline='\n').write(src)
    counts = {}
    for p in presets: counts[p['cat']] = counts.get(p['cat'], 0) + 1
    print(app, len(presets), 'presets ->', out)
    print('  ', ', '.join('%s %d' % (c, counts.get(c, 0)) for c in cats))

import factory_top, factory_low
emit('topend', 'topend', 'Top End', factory_top.PRESETS, factory_top.V1, factory_top.DEMOS, factory_top.CATS)
emit('lowend', 'lowend', 'Low End', factory_low.PRESETS, factory_low.V1, factory_low.DEMOS, factory_low.CATS)
