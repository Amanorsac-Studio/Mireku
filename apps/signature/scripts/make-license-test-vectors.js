// make-license-test-vectors.js — writes tests/LicenseVectors.h.
//
// Proofs shaped exactly like the studio licence server's (License Integration
// Standard §5), signed by Node's OpenSSL with THROWAWAY P-256 key pairs whose
// private halves are discarded when this script ends. The C++ verifier is then
// checked against an independent implementation, not against itself.
//
//   node apps/signature/scripts/make-license-test-vectors.js
'use strict';
const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const b64u = b => Buffer.from(b).toString('base64url');
function pair() {
  const { privateKey, publicKey } = crypto.generateKeyPairSync('ec', { namedCurve: 'P-256' });
  const jwk = publicKey.export({ format: 'jwk' });
  const raw = Buffer.concat([Buffer.from([4]), Buffer.from(jwk.x, 'base64url'), Buffer.from(jwk.y, 'base64url')]);
  return { privateKey, raw };
}
const sign = (k, bytes, enc = 'ieee-p1363') => crypto.sign('sha256', bytes, { key: k.privateKey, dsaEncoding: enc });
const proof = (k, obj) => { const body = Buffer.from(JSON.stringify(obj)); return b64u(body) + '.' + b64u(sign(k, body)); };

const studio = pair(), other = pair();
const ISSUED = 1793836800000;                 // 2026-11-05T00:00:00Z
const H = 3600000, D = 24 * H;
const DEV = '3f7c2a9e-6b1d-4e2f-9a8c-1d2e3f4a5b6c', KEY = 'MIRE-1A2B-3C4D-5E6F';
const base = { deviceKey: DEV, licenseKey: KEY, issuedAt: ISSUED, expiresAt: ISSUED + 48 * H, graceUntil: ISSUED + 30 * D };

const good = proof(studio, base);
const trial = proof(studio, { ...base, expiresAt: ISSUED + 48 * H, graceUntil: ISSUED + 5 * D,
                              licenseEndsAt: ISSUED + 5 * D, licenseKind: 'trial', futureField: { any: 1 } });
const otherDevice = proof(studio, { ...base, deviceKey: 'some-other-device-0001' });
const otherKey = proof(studio, { ...base, licenseKey: 'SECO-610E-6070-3493' });
const foreign = proof(other, base);
// The body changed after signing: one digit of graceUntil, re-encoded.
const [gb, gs] = good.split('.');
const tamperedBody = b64u(Buffer.from(Buffer.from(gb, 'base64url').toString().replace('"graceUntil":1796', '"graceUntil":1896'))) + '.' + gs;
const sig = Buffer.from(gs, 'base64url'); sig[40] ^= 1;
const tamperedSig = gb + '.' + b64u(sig);
const der = gb + '.' + b64u(sign(studio, Buffer.from(gb, 'base64url'), 'der'));
const n = Buffer.from('ffffffff00000000ffffffffffffffffbce6faada7179e84f3b9cac2fc632551', 'hex');
const sTooBig = gb + '.' + b64u(Buffer.concat([sig.subarray(0, 32), n]));
const zero = gb + '.' + b64u(Buffer.alloc(64));
// Re-serialised JSON with the same content but different bytes: must fail (§5 step 4).
const reserialised = b64u(Buffer.from(JSON.stringify(base, null, 1))) + '.' + gs;

// Raw signatures over random messages, to exercise the curve arithmetic broadly.
const raw = [];
for (let i = 0; i < 24; i++) {
  const k = i % 3 === 0 ? other : studio;
  const msg = crypto.randomBytes(1 + (i * 37) % 200);
  raw.push({ k: k === studio ? 0 : 1, msg: msg.toString('hex'), sig: sign(k, msg).toString('hex') });
}

const hexArr = b => Array.from(b).map(x => '0x' + x.toString(16).padStart(2, '0')).join(', ');
const q = s => '"' + s + '"';
let out = `// LicenseVectors.h — GENERATED by scripts/make-license-test-vectors.js. Do not edit.
// Signed by throwaway P-256 key pairs (private halves discarded). NOT the studio key.
#pragma once
namespace licensevectors {
constexpr long long kIssued = ${ISSUED}LL;   // 2026-11-05T00:00:00Z
constexpr long long kHour = ${H}LL, kDay = ${D}LL;
inline constexpr const char* kDevice = ${q(DEV)};
inline constexpr const char* kKey = ${q(KEY)};
inline constexpr unsigned char kPub[65] = { ${hexArr(studio.raw)} };
inline constexpr unsigned char kOtherPub[65] = { ${hexArr(other.raw)} };
`;
for (const [name, v] of Object.entries({ kGood: good, kTrial: trial, kOtherDevice: otherDevice, kOtherKey: otherKey,
  kForeign: foreign, kTamperedBody: tamperedBody, kTamperedSig: tamperedSig, kDer: der, kSTooBig: sTooBig,
  kZeroSig: zero, kReserialised: reserialised }))
  out += `inline constexpr const char* ${name} = ${q(v)};\n`;
out += `struct Raw { int key; const char* msg; const char* sig; };\ninline constexpr Raw kRaw[] = {\n` +
  raw.map(r => `    { ${r.k}, ${q(r.msg)}, ${q(r.sig)} },`).join('\n') + `\n};\n} // namespace licensevectors\n`;
fs.writeFileSync(path.join(__dirname, '..', 'tests', 'LicenseVectors.h'), out);
console.log('wrote tests/LicenseVectors.h');
